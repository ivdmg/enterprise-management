def test_seed_cli_execution_benchmark():
    """
    Validates BE-4.1: Seed CLI execution completes in < 3 seconds with code 0.
    """
    t0 = time.time()
    res = subprocess.run(
        ["python", "-m", "app.db.seed"],
        cwd="backend",
        capture_output=True,
        text=True,
    )
    elapsed = time.time() - t0
    assert res.returncode == 0, f"Seed CLI failed with stderr: {res.stderr}"
    assert elapsed < 3.0, f"Seed CLI took {elapsed}s, expected < 3.0s"


@pytest.mark.asyncio
async def test_seeded_data_integrity_and_endpoints():
    """
    Validates seeded database contents:
    - 5 projects (including 1 critical BG < 4 days, 1 overdue 44-FZ)
    - 15 procurement items
    - 8 dispatch records
    - 10 operational tasks
    - Active critical alerts for "Where is it burning?"
    - Validates GET /api/v1/dashboard/summary, /api/v1/dashboard/projects, /api/v1/procurement/items, /api/v1/tasks/operational.
    """
    from sqlalchemy.ext.asyncio import create_async_engine, async_sessionmaker, AsyncSession
    from sqlalchemy.pool import NullPool
    from app.core.config import settings

    test_engine = create_async_engine(settings.async_database_url, poolclass=NullPool)
    test_session_factory = async_sessionmaker(bind=test_engine, class_=AsyncSession, expire_on_commit=False)

    async with test_session_factory() as db:
        comp_q = select(Company).where(Company.inn == "7701234567")
        company = (await db.execute(comp_q)).scalars().first()
        assert company is not None, "Seeded company must exist"
        company_id = company.id

        # Check projects count
        proj_q = select(TenderProject).where(TenderProject.company_id == company_id)
        projects = (await db.execute(proj_q)).scalars().all()
        assert len(projects) == 5, f"Expected 5 projects, got {len(projects)}"

        # Check 1 project with BG critical
        crit_bg = [p for p in projects if p.risk_level.value == "critical" and p.bank_guarantee_expiry]
        assert len(crit_bg) >= 1, "Expected at least 1 project with critical bank guarantee risk"

        # Check 15 procurement items
        proc_q = select(ProcurementItem).where(ProcurementItem.company_id == company_id)
        proc_items = (await db.execute(proc_q)).scalars().all()
        assert len(proc_items) == 15, f"Expected 15 procurement items, got {len(proc_items)}"

        # Check 8 fleet dispatch units
        fleet_q = select(FleetDispatchRecord).where(FleetDispatchRecord.company_id == company_id)
        fleet_items = (await db.execute(fleet_q)).scalars().all()
        assert len(fleet_items) == 8, f"Expected 8 fleet dispatch records, got {len(fleet_items)}"

        # Check 10 operational tasks
        tasks_q = select(OperationalTask).where(OperationalTask.company_id == company_id)
        tasks = (await db.execute(tasks_q)).scalars().all()
        assert len(tasks) == 10, f"Expected 10 operational tasks, got {len(tasks)}"

        # Check critical alerts generated by Risk Engine
        alert_q = select(SystemAlert).where(
            SystemAlert.company_id == company_id,
            SystemAlert.is_resolved.is_(False),
            SystemAlert.severity == "CRITICAL",
        )
        crit_alerts = (await db.execute(alert_q)).scalars().all()
        assert len(crit_alerts) >= 2, f"Expected at least 2 critical alerts (BG + Procurement/44-FZ), got {len(crit_alerts)}"

        # Find admin user for auth token
        u_q = select(User).where(User.company_id == company_id)
        user = (await db.execute(u_q)).scalars().first()
        assert user is not None

    token = create_access_token(
        subject=str(user.id),
        company_id=str(company_id),
        role=user.role.value,
    )
    headers = {"Authorization": f"Bearer {token}"}

    from app.core.database import get_db

    async def override_get_db():
        async with test_session_factory() as s:
            try:
                yield s
                await s.commit()
            except Exception:
                await s.rollback()
                raise

    app.dependency_overrides[get_db] = override_get_db

    transport = ASGITransport(app=app)
    try:
        async with AsyncClient(transport=transport, base_url="http://test") as client:
            # 1. /api/v1/dashboard/summary
            resp_summary = await client.get("/api/v1/dashboard/summary", headers=headers)
            assert resp_summary.status_code == 200
            summary_data = resp_summary.json()["data"]
            assert "free_cash" in summary_data
            assert "active_portfolio_sum" in summary_data
            assert summary_data["critical_alerts_count"] >= 2
            assert len(summary_data["top_fire_items"]) >= 2

            # 2. /api/v1/dashboard/projects
            resp_projects = await client.get("/api/v1/dashboard/projects", headers=headers)
            assert resp_projects.status_code == 200
            projects_data = resp_projects.json()["data"]
            assert len(projects_data) == 5
            assert any(p["bg_risk_level"] == "critical" for p in projects_data)

            # 3. /api/v1/procurement/items
            resp_proc = await client.get("/api/v1/procurement/items", headers=headers)
            assert resp_proc.status_code == 200
            proc_data = resp_proc.json()["data"]
            assert len(proc_data) == 15

            # 4. /api/v1/tasks/operational
            resp_tasks = await client.get("/api/v1/tasks/operational", headers=headers)
            assert resp_tasks.status_code == 200
            tasks_data = resp_tasks.json()["data"]
            assert len(tasks_data) == 10
    finally:
        app.dependency_overrides.clear()
        await test_engine.dispose()
